"""A deterministic frequency mechanism and a temporal discriminator.

One persistent cyclic counter per incoming tag at each gate occurrence
replaces independent uniform seeds. It is an alternative interpretation
of a FIXED repeated source/circuit; this is not detector noise, a random
state preparation, an iid sampling theorem, or prediction of real clicks.
"""

import sys
from collections import Counter
from fractions import Fraction as F
from itertools import pairwise, product
from math import prod
from pathlib import Path

if not __package__:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.probe_cancellation_event_router import (
    PLATE,
    Cloud,
    H,
    Matrix,
    Pair,
    embedded,
    need,
    pairs,
    route_block,
)
from scripts.probe_native_recurrence_witness import native_prefix

Routes = dict[tuple[Pair, int], Pair]
Stage = tuple[Routes, int]


def prepare(word: tuple[Matrix, ...], reverse: bool) -> tuple[Cloud, list[Stage]]:
    cloud: Cloud = ((0, 1),)
    stages: list[Stage] = []
    for gate in word:
        cloud, routes, h, _ = route_block(cloud, gate, reverse)
        stages.append((routes, h))
    return cloud, stages


def stream(stages: list[Stage], trials: int, mode: str, offset: int) -> list[Pair]:
    counters: dict[tuple[int, Pair], int] = {}
    result = []
    for t in range(trials):
        p = (0, 0)
        clock = t + offset
        for j, (routing, h) in enumerate(stages):
            if mode == "synchronized":
                seed, clock = clock % h, clock // h
            else:
                key = (j, p if mode == "per-tag" else (0, 0))
                if mode == "reset":
                    seed = offset % h
                else:
                    need(mode in ("per-tag", "per-gate"), "unrecognized mechanism")
                    seed = (
                        counters.get(
                            key, offset * (1 + 3 * key[1][0] + 5 * key[1][1] + j)
                        )
                        % h
                    )
                    counters[key] = (seed + 1) % h
            p = routing[p, seed]
        result.append(p)
    return result


def thinning(efficiency: F) -> tuple[F, F, F]:
    """Stationary rotor 0011; keep each trial independently at the same rate.

    First detected phase is uniform (e.g. stationarity or time averaging);
    each subsequent gap is geometric. Losses here are a supplied stochastic
    observation model, not generated by the deterministic rotor.
    """
    need(0 < efficiency <= 1, "invalid observed efficiency")
    t = 1 - efficiency
    jump = [efficiency * t**j / (1 - t**4) for j in range(4)]
    need(sum(jump) == 1, "gap normalization")
    balanced = all_left = consecutive_left = F(0)
    for a, b, c, d in product(range(4), repeat=4):
        seq = (a, b, c, d)
        weight = F(1, 4) * prod(jump[(y - x - 1) % 4] for x, y in pairwise(seq))
        left = sum(x < 2 for x in seq)
        if left == 2:
            balanced += weight
        if left == 4:
            all_left += weight
        if a < 2 and b < 2:
            consecutive_left += weight
    return balanced, all_left, 2 * consecutive_left


def exact_sampling_cost() -> None:
    """Uniform seed denominator vs *average* fair-coin cost of a known target.

    With pi=1+i, the integer matrix for pi² T12 T01 has rows
    (i*pi,pi,0), (i,-1,pi), (1,i,i*pi). Modulo pi the injected e0
    maps to (0,1,1), which is fixed. The first numerator at t>=1 is
    pi*(i*previous_0 + previous_1) with the factor in parentheses a
    unit mod pi in BOTH predecessor cases. Its norm cancels exactly
    one power of two from 2^(2t). See the direct, separate recurrence.
    """
    probabilities = native_prefix(128)
    for t, p in enumerate(probabilities[1:], 1):
        d = 2 * t - 1
        need(p.denominator == 2**d, "uniform seed denominator")
        if d > 11:
            continue
        hist: Counter[int] = Counter()
        clicks = 0
        for sample in range(2**d):
            # Prefix interval [lo,hi) lies on one side of the threshold:
            # no further fair bits are needed. Not native event routing.
            for bits in range(1, d + 1):
                step = 2 ** (d - bits)
                lo = (sample // step) * step
                if lo >= p.numerator or lo + step <= p.numerator:
                    hist[bits] += 1
                    clicks += int(lo < p.numerator)
                    break
        mean = F(sum(k * v for k, v in hist.items()), 2**d)
        need(clicks == p.numerator and sum(hist.values()) == 2**d, "exact probability")
        need(max(hist) == d and mean == 2 - F(2, 2**d), "worst vs mean resource")
    print("Native returns, t=1..128: exact reduced denominator 2^(2t-1).")
    print(
        "Fixed-depth uniform stock must have that divisor; fresh target-aware fair-coin mean is <2, not an exponential runtime lower bound."
    )


def main() -> None:
    cases = 0
    words = ((H,), (H, H), (H, PLATE, H), (embedded(0, 2), embedded(2, 2)))
    for word in words:
        for rev in (False, True):
            cloud, stages = prepare(word, rev)
            period = prod(h for _, h in stages)
            need(period == len(pairs(cloud)), "unique input address")
            for mode, offset in product(("per-tag", "synchronized"), range(6)):
                seq = stream(stages, 3 * period, mode, offset)
                for start in range(2 * period + 1):
                    need(
                        Counter(seq[start : start + period])
                        == Counter({p: 1 for p in pairs(cloud)}),
                        "sliding complete cycle",
                    )
                cases += 1
    cloud, stages = prepare(words[-1], False)
    controls = {}
    for mode in ("per-tag", "synchronized", "per-gate", "reset"):
        out = stream(stages, 16, mode, 0)
        hist = Counter(cloud[p[0]][0] // 2 for p in out)
        controls[mode] = tuple(hist[i] for i in range(3))
    need(
        controls["per-tag"] == controls["synchronized"] == (8, 4, 4),
        "three-port frequency",
    )
    need(
        controls["per-gate"] == (8, 0, 8) and controls["reset"] == (16, 0, 0),
        "hidden timing dependence",
    )
    cloud, stages = prepare((H,), False)
    arms = [cloud[p[0]][0] // 2 for p in stream(stages, 12, "per-tag", 0)]
    need(arms == [0, 0, 1, 1] * 3, "tag order and chosen offset")
    iid = sum(1 for s in product(range(2), repeat=4) if sum(s) == 2) * F(1, 16)
    need(
        iid == F(3, 8) and thinning(F(1)) == (F(1), F(0), F(1, 2)),
        "ideal timing contrast",
    )
    balanced, all_left, lag_one = thinning(F(1, 2))
    need(
        0 < balanced < 1 and all_left >= F(1, 128) and lag_one == F(2, 5),
        "thinned timing control",
    )
    print(
        f"{cases} circuits/matchings/offsets/schedules: every sliding product-gain window visits every terminal tag once."
    )
    print(f"Three-port counts, 16 source injections: {controls}")
    print(
        "Four successive ideal triggers: rotor exactly 2:2 with probability 1 vs independent fair clicks 3/8."
    )
    print(
        f"Same rotor after iid 50% thinning: P(2:2)={balanced}, P(LLLL)={all_left}, P(next L | L)={lag_one}."
    )
    print(
        "Persistent local counters or a synchronized clock supplied; pooled counts alone cannot choose a sampling mechanism."
    )
    exact_sampling_cost()


if __name__ == "__main__":
    main()
