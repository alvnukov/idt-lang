"""An unsigned two-mark rule induces the raw mixer only with a collision contract.

Select two distinct incident legs and replace their unordered marks with the
two unused legs. The rule is permutation equivariant, does not refer to
sign, amplitude or a norm, and is nontrivial only at valency four in this
class of deterministic pair-to-pair rewrites (see the companion note).
Supply disjoint unlike pairs exhausting the input and an oriented four-cycle
of the outgoing wires. This gives T on *count deviations* about a uniform
background. A uniformly random pairing with equal pairs left undisturbed
normally does not give T. Retain count, hidden pairing, clock, attenuation,
and detector assumptions separately. No simulated counts are physical data.
"""

from __future__ import annotations

import sys
from collections import Counter
from fractions import Fraction as F
from itertools import combinations, combinations_with_replacement, permutations
from math import comb, factorial, prod
from pathlib import Path

if not __package__:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.gaussian_dyadic_words import CROSS, DIAG, ZERO, Gaussian, g
from scripts.probe_chain_relational_charge import PAIRS, faithful_gates

Edge = tuple[int, int]
Counts = tuple[int, int, int, int]
EDGES = tuple(combinations(range(4), 2))


def require(ok: bool, msg: str) -> None:
    if not ok:
        raise ArithmeticError(msg)


def collide(i: int, j: int) -> Edge:
    if not 0 <= i < 4 or not 0 <= j < 4:
        raise ValueError("four incident legs required")
    if i == j:
        return i, j
    k, l = (x for x in range(4) if x != i and x != j)
    return k, l


def counts(pairs: tuple[Edge, ...]) -> Counts:
    h = Counter(mark for edge in pairs for mark in edge)
    if set(h) - set(range(4)):
        raise ValueError("unknown leg")
    return h[0], h[1], h[2], h[3]


def pairing(n: Counts) -> tuple[Edge, ...]:
    """One existence witness: sort legs and pair tokens half a list apart."""
    if min(n) < 0 or sum(n) % 2 or 2 * max(n) > sum(n):
        raise ValueError("not an exhaustive unlike-pair histogram")
    n2 = sum(n) // 2
    tokens = tuple(i for i, m in enumerate(n) for _ in range(m))
    return tuple(zip(tokens[:n2], tokens[n2:], strict=True))


def output(pairs: tuple[Edge, ...]) -> Counts:
    h = counts(tuple(collide(i, j) for i, j in pairs))
    return h[1], h[2], h[3], h[0]


def balanced_turn(x: tuple[F, ...]) -> tuple[F, ...]:
    if len(x) != 4:
        raise ValueError("four ordered leg counts required")
    half = sum(x, F(0)) / 2
    return tuple(half - x[(i + 1) % 4] for i in range(4))


def random_unturned(n: Counts) -> tuple[F, ...]:
    """Expected pre-wiring counts for uniform random perfect matching, equals transparent."""
    size = sum(n)
    if min(n) < 0 or size < 2 or size % 2:
        raise ValueError("even positive number of marks required")
    like = tuple(F(x * (x - 1), 2 * (size - 1)) for x in n)
    return tuple(
        F(size, 2) - x + 4 * t - sum(like) for x, t in zip(n, like, strict=True)
    )


def matchings(v: tuple[int, ...]) -> list[tuple[Edge, ...]]:
    if not v:
        return [()]
    return [
        ((v[0], v[j]), *tail)
        for j in range(1, len(v))
        for tail in matchings(v[1:j] + v[j + 1 :])
    ]


def reversible_history_cost(m: int) -> tuple[F, int]:
    """Uniform initial *labeled pairings*, m marks each of two colors.

    Not a thermodynamic bound on free marks or on an already prepaired
    source: those are different input domains. Minimum flag alphabet for an
    injective encoding in valid matching x flag, with no further constraints.
    """
    if m < 0:
        raise ValueError("negative multiplicity")
    total = prod(range(1, 2 * m, 2))
    valid = factorial(m)
    chance = F(valid, total)
    require(chance == F(2**m, comb(2 * m, m)), "counting identity")
    return chance, (total + valid - 1) // valid


def symmetries() -> None:
    for d in range(2, 8):
        edges = set(combinations(range(d), 2))
        # Stabilizer of input {0,1} is generated by swaps inside the two parts.
        fixed = set(edges)
        for j, k in ((0, 1), *zip(range(2, d - 1), range(3, d), strict=True)):
            perm = list(range(d))
            perm[j], perm[k] = perm[k], perm[j]
            fixed = {e for e in fixed if set(e) == {perm[t] for t in e}}
        require(
            fixed == ({(0, 1), (2, 3)} if d == 4 else {(0, 1)}),
            "pair-rule classification",
        )
    gs = faithful_gates()
    for gate in gs:
        require(
            all(sorted(gate[i, j]) == list(collide(i, j)) for i, j in PAIRS),
            "old rule mismatch",
        )
        aut = [
            p
            for p in permutations(range(4))
            if all(
                tuple(p[k] for k in gate[i, j]) == gate[p[i], p[j]] for i, j in PAIRS
            )
        ]
        require(
            len(aut) == 3 and sum(all(p[i] == i for p in aut) for i in range(4)) == 1,
            "ordered symmetry",
        )


def matching_controls() -> int:
    checked = 0
    for k in range(7):
        for packet in combinations_with_replacement(EDGES, k):
            n = counts(packet)
            direct = output(packet)
            real_direct = tuple(map(F, direct))
            x = tuple(map(F, n))
            require(
                direct == output(pairing(n)) and real_direct == balanced_turn(x),
                "matching dependence",
            )
            require(balanced_turn(balanced_turn(x)) == x[2:] + x[:2], "two ticks")
            require(sum(t * t for t in direct) == sum(t * t for t in n), "square norm")
            z, w = g(n[0], n[1]), g(n[2], n[3])
            a, b = DIAG * z + CROSS * w, CROSS * z + DIAG * w
            require(real_direct == (a.re, a.im, b.re, b.im), "raw Gaussian table")
            checked += 1
    for n in ((3, 1, 2, 2), (2, 2, 2, 2), (4, 1, 1, 2), (2, 0, 1, 1)):
        tokens = tuple(i for i, v in enumerate(n) for _ in range(v))
        ways = matchings(tokens)
        av = tuple(
            sum(
                (counts(tuple(collide(i, j) for i, j in pairs))[k] for pairs in ways), 0
            )
            * F(1, len(ways))
            for k in range(4)
        )
        require(av == random_unturned(n), "uniform matching expectation")
    # Identical input histogram; choosing equal pairs can change the output.
    one = ((0, 0), (1, 2))
    two = ((0, 1), (0, 2))
    require(counts(one) == counts(two) and output(one) != output(two), "schedule wall")
    for bkg in (1, 2, 4, 16, 100):
        # Exact antisymmetric finite difference. The equal-pair quadratic
        # bias cancels in this odd response; no continuum approximation.
        hi = random_unturned((bkg + 1, bkg - 1, bkg, bkg))
        lo = random_unturned((bkg - 1, bkg + 1, bkg, bkg))
        require((hi[0] - lo[0]) / 2 == F(-1, 4 * bkg - 1), "random matching signal")
    return checked


def repeated(depth: int) -> tuple[tuple[Gaussian, ...], ...]:
    if depth < 0:
        raise ValueError("nonnegative depth required")
    state: tuple[Gaussian, ...] = (g(1), ZERO, ZERO)
    path = [state]
    for _ in range(depth):
        for j, k in ((0, 1), (1, 2)):
            a, b = state[j], state[k]
            out = list(state)
            out[j], out[k] = DIAG * a + CROSS * b, CROSS * a + DIAG * b
            state = tuple(out)
            path.append(state)
    return tuple(path)


def occupancy_prefix(t: int) -> None:
    if not 0 <= t <= 10:
        raise ValueError("bounded explicit mark replay supports depths 0 through 10")
    budget = 2**t
    path = repeated(t)
    n = [budget + budget * int(i == 0) for i in range(6)]
    for s, ((j, k), v) in enumerate(
        zip(((0, 1), (1, 2)) * t, path[1:], strict=True), start=1
    ):
        rr = (2 * j, 2 * j + 1, 2 * k, 2 * k + 1)
        local = (n[rr[0]], n[rr[1]], n[rr[2]], n[rr[3]])
        h = output(pairing(local))
        for i, value in zip(rr, h, strict=True):
            n[i] = value
        expected = tuple(budget + budget * x for z in v for x in (z.re, z.im))
        require(
            tuple(n) == expected and sum(n) == 7 * budget and min(n) >= 0,
            "integer replay",
        )
        require(
            max(x.denominator for z in v for x in (z.re, z.im)) == 2 ** ((s + 1) // 2),
            "least common scale",
        )


def main() -> None:
    symmetries()
    n = matching_controls()
    for t in range(11):
        occupancy_prefix(t)
    for m in range(1, 6):
        ways = matchings((0,) * m + (1,) * m)
        chance, flags = reversible_history_cost(m)
        valid = sum(all(i != j for i, j in edges) for edges in ways)
        require(
            chance == F(valid, len(ways))
            and (flags - 1) * valid < len(ways) <= flags * valid,
            "matching entropy domain",
        )
    print(
        f"Valency-four complementary-pair rewrite: {n} complete packet histograms checked counting multiplicities. One chosen cyclic wiring produces the native mixer on unsigned counts about a background; two ticks exchange port pairs."
    )
    print(
        "Equal pairs left intact under uniform random matching: odd one-mark response is -1/(4B-1), versus -1 for unlike-pair completion. Identical histograms can yield different outcomes."
    )
    print(
        "Three ports, alternating two native collisions t times: least integer common signal scale 2^t, checked by actual unsigned mark replays to t=10. Matching, wiring, preparation and a detector of deviations remain supplied."
    )
    chance, flags = reversible_history_cost(16)
    print(
        f"Separately, accepting every labeled pre-pairing of 16+16 two-color marks leaves only fraction {chance} already unlike. A reversible repair into those matchings must distinguish at least {flags} flag values. No cost is inferred for a source already supplying its pairing."
    )


if __name__ == "__main__":
    main()
