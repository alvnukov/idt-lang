"""What does a direct free-neutron measurement distinguish on the supplied charge plane?

Inputs, not IDT outputs: the six one-family left-Weyl representations, the
ordinary anomaly conditions, one scalar doublet and charge-conserving Yukawa
links of probe_packet_charge_pairings. Use integer U(1) characters; q is the
quark-doublet character, h>0 the independently oriented scalar character.
Require the conventional diagonal Z6 quotient, q=1 mod 6, h=3 mod 6.
Supply a neutral lower Higgs component, T3 doublet eigenvalues ±1/2, and
electromagnetic readout T3+y/(2h). Identify proton/neutron charges with
the additive valence uud/udd charges. No particle, confinement, measurement
operator, or charge lattice normalization is derived from packet primitives.
Use electron units only when the electron is charged (3q+h nonzero).

With these inputs hydrogen (one proton + one electron) is neutral for the
whole plane and Q_n=-Q_nu. For fixed h=3, q=1+6n gives |Q_n/Q_e| =
3|n|/|1+3n|. For n>=1 this is at least 3/4, equality at n=1; for n<=-1
it exceeds 1. This is an exact gap for all integers, NOT a finite scan.

The measured estimate is (-0.4 ± 1.1) x 10^-21 electron charges, from cold
neutron beam deflection in a 9 m electric field region: Baumann, Gähler,
Kalus and Mampe (1988), https://doi.org/10.1103/PhysRevD.37.3107 .
We compare magnitudes and quoted uncertainty; no absolute limit, confidence
level, or Gaussian likelihood is inferred. The only fixed-h=3 lattice
member within the quoted interval is n=0. This is empirical discrimination
of a supplied model family, not a first-principles determination of charge.

If only the quotient is fixed, q=1+6n, h=3q+6 (n>=0) gives a primitive
integer character assignment with exactly the same Z6 kernel, yet signed
Q_n/|Q_e|=-1/(q+1). These are inequivalent ratios, not rescalings. Every
finite neighborhood of zero contains nonzero examples; no fitted candidate
or physical preference for very large weights is asserted.

Bressi et al.'s independent acoustic bulk-matter measurement is NOT another
direct neutron measurement. Its standard single-parameter reduction assumes
charge conservation in neutron beta decay AND antineutrino neutrality (intro
after Eq. 1, https://arxiv.org/html/1102.2766 ). The latter fails for these
nonzero examples. The raw observable can still be analyzed under a specified
composition model; their converted limit is not used here.

Run: python3 -B -O -m scripts.probe_neutron_charge_anchor
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction as F
from math import ceil, gcd


def require(ok: bool, why: str) -> None:
    if not ok:
        raise ArithmeticError(why)


# Coefficients of q and h for Q, u^c, d^c, L, e^c, N^c, H, in that order.
Form = tuple[int, int]
Y: tuple[Form, ...] = ((1, 0), (-1, -1), (-1, 1), (-3, 0), (3, 1), (3, -1), (0, 1))
TRIALITY = (1, -1, -1, 0, 0, 0, 0)
WEAK = (1, 0, 0, 1, 0, 0, 1)
MEASURED = F(-4, 10**22)
QUOTED_WIDTH = F(11, 10**22)


def kernel_certificate() -> None:
    """Algebraic kernel of the product action on these fields, not a line-operator test.

    For a putative kernel element (A,B,z), acting on H forces B=z^(-h) I2;
    Q then forces A=z^(h-q) I3. There are no untested noncentral candidates.
    Each remaining condition says z^exponent=1. Show their integer span is
    generated by 2h and 3q+h: necessary (det B and e^c) and sufficient.
    Thus projection to z identifies the full kernel with mu_gcd(2h,3q+h).
    """
    field_exponents = tuple(
        (a - t, b + t - w) for (a, b), t, w in zip(Y, TRIALITY, WEAK, strict=True)
    )
    exponents = field_exponents + ((-3, 3), (0, -2))  # det A, det B
    coeffs = (
        (0, 0),
        (-1, 0),
        (0, 0),
        (0, -1),
        (0, 1),
        (-1, 1),
        (0, 0),
        (2, -1),
        (-1, 0),
    )
    # r*(2h) + s*(3q+h) has coefficients (3s, 2r+s).
    require(
        exponents == tuple((3 * s, 2 * r + s) for r, s in coeffs), "kernel sufficiency"
    )
    require(exponents[4] == (3, 1) and exponents[-1] == (0, -2), "kernel necessity")


def kernel_order(q: int, h: int) -> int:
    return gcd(2 * h, 3 * q + h)


def check_quotient(q: int, h: int) -> None:
    require((q % 6, h % 6) == (1, 3) and h > 0, "outside the oriented lattice")
    require(kernel_order(q, h) == 6, "additional ineffective center")
    # z=exp(2pi i/6) acts with A=z^(h-q) I3 = omega I3, B=z^(-h) I2 = -I2.
    require(((h - q) % 6, (-h) % 6) == (2, 3), "wrong order-six embedding")


@dataclass(frozen=True)
class Readout:
    proton: F
    neutron: F
    electron: F
    neutrino: F

    def neutron_in_electron_units(self) -> F:
        return self.neutron / abs(self.electron)


def readout(q: int, h: int) -> Readout:
    require(h > 0, "choose positive scalar orientation")
    require(3 * q + h != 0, "cannot normalize to a neutral electron")
    yq, yu, yd, yl, ye, yn, yh = (a * q + b * h for a, b in Y)
    unit = F(1, 2 * h)
    half = F(1, 2)
    up, down = half + unit * yq, -half + unit * yq
    nu, electron = half + unit * yl, -half + unit * yl
    require(-half + unit * yh == 0, "H lower component is not neutral")
    require(
        (up, down, nu, electron) == tuple(-unit * y for y in (yu, yd, yn, ye)),
        "left and right physical electric charges disagree",
    )
    result = Readout(2 * up + down, up + 2 * down, electron, nu)
    require(
        result.proton + electron == 0 and result.neutron == -nu, "neutrality identities"
    )
    require(
        result.neutron_in_electron_units() == F(3 * q - h, abs(3 * q + h)),
        "normalized charge",
    )
    return result


def fixed_weight(n: int) -> F:
    q, h = 1 + 6 * n, 3
    # For all integers n, gcd(6,6+18n)=6 and 3q+h never vanishes.
    check_quotient(q, h)
    ratio = abs(readout(q, h).neutron_in_electron_units())
    require(ratio == F(3 * abs(n), abs(1 + 3 * n)), "fixed-weight ratio")
    if n > 0:
        # 4*(3n)-3*(1+3n)=3(n-1)>=0, equality only at n=1.
        require(
            12 * n - 3 * (1 + 3 * n) == 3 * (n - 1) >= 0 and ratio >= F(3, 4),
            "positive branch",
        )
    elif n < 0:
        require(3 * abs(n) == abs(1 + 3 * n) + 1 and ratio > 1, "negative branch")
    else:
        require(ratio == 0, "standard-line anchor")
    return ratio


def near_zero(n: int) -> F:
    require(n >= 0, "nonnegative sequence parameter")
    q = 1 + 6 * n
    h = 3 * q + 6
    # gcd(q,h)=gcd(q,6)=1. A common positive rescaling cannot explain this family.
    # Also (2h)-(3q+h)=6 and both are multiples of 6: exactly six kernel elements.
    require(gcd(q, h) == 1 and 2 * h - (3 * q + h) == 6, "primitive coprime control")
    check_quotient(q, h)
    ratio = readout(q, h).neutron_in_electron_units()
    require(ratio == -F(1, q + 1), "variable-weight family")
    return ratio


def inside_precision(precision: F) -> F:
    """Construct a nonzero witness for ANY positive rational resolution around zero."""
    require(precision > 0, "need positive resolution")
    n = ceil(1 / (6 * precision))
    # 6n+2 > 1/precision gives strict inclusion, including exact integer thresholds.
    ratio = near_zero(n)
    require(0 < abs(ratio) < precision, "finite-precision witness")
    return ratio


def main() -> None:
    kernel_certificate()
    require(
        fixed_weight(0) == 0
        and fixed_weight(1) == F(3, 4)
        and fixed_weight(-1) == F(3, 2),
        "fixed-weight edge cases",
    )
    # Guard against downgrading "exactly Z6" to mere Z6 compatibility.
    require(
        (7 % 6, 21 % 6) == (1, 3) and kernel_order(7, 21) == 42,
        "enlarged-kernel control",
    )
    require(near_zero(0) == -F(1, 2) and near_zero(1) == -F(1, 8), "not a rescaling")
    # A symmetric subinterval is safe independently of the sign convention for 'e'.
    inner = QUOTED_WIDTH - abs(MEASURED)
    outer = QUOTED_WIDTH + abs(MEASURED)
    require(inner > 0 and outer < F(3, 4), "published interval versus fixed gap")
    delta = inside_precision(inner)
    require(
        abs(delta - MEASURED) < QUOTED_WIDTH and abs(-delta - MEASURED) < QUOTED_WIDTH,
        "nonzero witness within either sign convention",
    )
    print(
        "Supplied charge readout: protium (p+e) neutral throughout; neutron charge = minus neutrino charge."
    )
    print(
        "Fixed independent h=3: n=0 has zero neutron charge; every other integer has |Qn/Qe| >= 3/4."
    )
    print(
        "Direct free-neutron estimate: (-0.4 ± 1.1) × 10^-21 electron charges; only n=0 lies in the quoted band."
    )
    print(
        "Fix only the diagonal Z6: primitive h=3q+6 gives |Qn/Qe|=1/(q+1)>0 arbitrarily close to zero."
    )
    print(
        "Conditional empirical discriminator; neither exact neutrality nor the Higgs weight is derived from packets."
    )


if __name__ == "__main__":
    main()
