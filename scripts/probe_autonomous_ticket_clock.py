"""Full counting clocks on four-port square tickets with a fixed reference.

Domain: four signed integer fields x with EVEN total, so Sx=(sum x)/2-x
is integral. At x there are N=sum x_i^2 tickets (i,a,b), 0<=a,b<|x_i|.
Port permutations act on i alone. The scattering step must be a bijection
between the x and Sx tickets, invert on a second step, and preserve a
supplied S4 reference r. At every nonempty fixed field an additional command
must be a SINGLE directed cycle on all its tickets, using the SAME r.
Both commands are equivariant and our construction makes them commute.

Lower bound on any admissible reference orbit: the stabilizer K of r at
the all-ones field must commute with the four-ticket clock, so it lies in
the cyclic centralizer of a four-cycle. If |K|=4, take the alternating
field on its generating cycle. That generator exchanges x and Sx, acting
as one four-cycle on their combined four tickets. A commuting involution
could only be the identity or the half-turn; neither exchanges the fields.
Thus |K|<=2 and the orbit has at least 12 reference states. This obstruction
does not even need commutation between the two device commands.

Construction on the whole even-total lattice: take H generated by a double
transposition, R=S4/H (12 states). At reference H choose a cyclic coordinate
on each fiber such that H's nonidentity h adds N/2 when it transports a
ticket to the hx fiber. This is possible because N is even; on an h-fixed
field h acts freely in pairs. Tick adds one; scatter transports the index
unchanged to Sx (equal norm). Both commute with h and with one another;
induce to every reference by changing chart. This is a choice of nonlocal
fiber orders, not a nearest-neighbor mechanism, minimal total device memory,
or a derivation of square tickets. Repeatable inspection of a static field
for a whole period yields exact counts, not an unbiased one-shot sample.
"""

from __future__ import annotations

import json
from functools import cache
from itertools import permutations, product

PORTS = tuple(range(4))
G = tuple(permutations(PORTS))
I = PORTS
H = (1, 0, 3, 2)
C = (1, 2, 3, 0)
V4 = (I, H, (2, 3, 0, 1), (3, 2, 1, 0))


def need(ok, message):
    if not ok:
        raise ArithmeticError(message)


def mul(g, h):
    return tuple(g[i] for i in h)


def inv(g):
    return tuple(g.index(i) for i in PORTS)


def ref(g):
    return min(g, mul(g, H))


def field(g, x):
    return tuple(x[i] for i in inv(g))


def ticket(g, t):
    return g[t[0]], t[1], t[2]


def scatter(x):
    if len(x) != 4 or any(type(v) is not int for v in x) or sum(x) % 2:
        raise ValueError("expected four integer fields with even total")
    mean_twice = sum(x)//2
    return tuple(mean_twice-v for v in x)


def tickets(x):
    scatter(x)  # validate before enumerating
    return tuple((i, a, b) for i, v in enumerate(x) for a, b in product(range(abs(v)), repeat=2))


@cache
def base_cycle(x):
    """List in index order. Empty fiber has NO clock or sampled probability."""
    hx = field(H, x)
    ts = tickets(x)
    n = len(ts)
    need(n % 2 == 0, "parity of sum of squares")
    if x < hx:
        return ts
    if x == hx:
        half = tuple(t for t in ts if t < ticket(H, t))
        return half + tuple(ticket(H, t) for t in half)
    mates = tuple(ticket(H, t) for t in base_cycle(hx))
    return mates[n//2:] + mates[:n//2]


@cache
def cycle(r, x):
    return tuple(ticket(r, t) for t in base_cycle(field(inv(r), x)))


def orbit(start, successor):
    seen = set()
    here = start
    while here not in seen:
        seen.add(here)
        here = successor(here)
    need(here == start, "not a cycle through initial state")
    return seen


def lower_controls():
    cyclic = {I, C, mul(C, C), mul(C, mul(C, C))}
    need({g for g in G if mul(g, C) == mul(C, g)} == cyclic, "centralizer of a four-cycle")
    all_cycles = [g for g in G if len(orbit(0, g.__getitem__)) == 4]
    need(len(all_cycles) == 6 and all(not all(mul(h, g) == mul(g, h) for h in V4) for g in all_cycles),
         "six-frame Klein reference must fail the clock at all ones")
    x = (1, 0, 1, 0)
    y = scatter(x)
    need(field(C, x) == y and len(tickets(x)) == len(tickets(y)) == 2, "alternating-field control")
    commuting_exchangers = [g for g in cyclic if field(g, x) == y]
    need(len(commuting_exchangers) == 2 and all(mul(g, g) != I for g in commuting_exchangers),
         "cyclic reference can tick but cannot support involutive scattering")
    # Every residual port stabilizer must act freely: (2,0,0,0) has 4
    # tickets on one port, but its scattered partner has one at EVERY port.
    # A transposition fixing the localized port fixes 4 vs 2 tickets.
    loc = (2, 0, 0, 0)
    fix = (0, 2, 1, 3)
    need(field(fix, loc) == loc and [sum(ticket(fix, t) == t for t in tickets(z))
                                      for z in (loc, scatter(loc))] == [4, 2], "fixed-ticket obstruction")
    return {"all_ones_four_cycles": 6, "Klein_four_admissible_four_cycles": 0,
            "cyclic_four_equivariant_alternating_exchanges": len(commuting_exchangers),
            "involutive_among_them": 0, "orbit_lower_bound": 12}


def six_frame_comparison(xs):
    # Independent existence test for transport alone at a V4 reference.
    # If Sx=h x in its V4 orbit, use the same h throughout this orbit:
    # V4 commutes and h^2=id. Otherwise Kx=K_Sx and the two fibers have
    # the same number of free Kx-orbits. Pair orbit representatives, extend
    # equivariantly, then induce to V4-translates and use the inverse back.
    internal = external = 0
    for x in xs:
        y = scatter(x)
        if any(field(g, x) == y for g in V4):
            internal += 1
            continue
        kx = tuple(g for g in V4 if field(g, x) == x)
        need(kx == tuple(g for g in V4 if field(g, y) == y), "scatter stabilizer")
        orbits = []
        for z in (x, y):
            sets = {frozenset(ticket(g, t) for g in kx) for t in tickets(z)}
            need(all(len(s) == len(kx) for s in sets), "nonfree ticket stabilizer")
            orbits.append(len(sets))
        need(orbits[0] == orbits[1], "unequal orbit types for transport")
        external += 1
    return {"same_Klein_field_orbit": internal, "distinct_pairable_Klein_field_orbits_counted_by_fields": external}


def probe():
    box = {x for x in product(range(-2, 3), repeat=4) if sum(x) % 2 == 0}
    xs = box | {scatter(x) for x in box}
    refs = sorted({ref(g) for g in G})
    need(len(refs) == 12 and all(scatter(scatter(x)) == x for x in xs), "frame index / scatter closure")
    sx = {x: scatter(x) for x in xs}
    ticks, jumps = {}, {}
    total = nonempty = 0
    for r, x in product(refs, sorted(xs)):
        ts = cycle(r, x)
        ys = cycle(r, sx[x])
        n = len(ts)
        need(n == sum(v*v for v in x) and set(ts) == set(tickets(x)) and len(ys) == n, "square stock")
        ticks[r, x] = dict(zip(ts, ts[1:] + ts[:1], strict=True))
        jumps[r, x] = dict(zip(ts, ys, strict=True))
        if n:
            nonempty += 1
            need(orbit(ts[0], ticks[r, x].__getitem__) == set(tickets(x)), "not one full clock")
        total += n
    equiv = 0
    for (r, x), tick in ticks.items():
        y, jump = sx[x], jumps[r, x]
        need(all(jumps[r, y][z] == t and ticks[r, y][z] == jump[tick[t]] for t, z in jump.items()),
             "inverse or commuting square failed")
        for g in G:
            s, gx = ref(mul(g, r)), field(g, x)
            target_tick, target_jump = ticks[s, gx], jumps[s, gx]
            for t, z in jump.items():
                gt = ticket(g, t)
                need(target_jump[gt] == ticket(g, z) and target_tick[gt] == ticket(g, tick[t]),
                     "port renaming while transforming the same retained reference")
            equiv += len(jump)
    loc = (2, 0, 0, 0)
    r = ref(I)
    def clock_and_scatter(pair):
        x, t = pair
        return sx[x], jumps[r, x][ticks[r, x][t]]
    combined = orbit((loc, cycle(r, loc)[0]), clock_and_scatter)
    observed = sorted(t[0] for x, t in combined if x == sx[loc])
    need(len(combined) == 4 and len(set(observed)) == 2, "alternating-field sampling alias control")
    # Even an explicitly uniform random starting phase gives uniform
    # one-time margins, but not iid draws or exchangeable histories.
    ones = (1, 1, 1, 1)
    pairs = {(t[0], u[0]) for t, u in ticks[r, ones].items()}
    need(len(pairs) == 4 and all((b, a) not in pairs for a, b in pairs), "directional two-read histories")
    for malformed in ((1, 0, 0, 0), (True, 1, 0, 0), (0, 0, 0)):
        try:
            scatter(malformed)
        except ValueError:
            continue
        raise ArithmeticError("accepted malformed field")
    return {"scope": "finite_square_ticket_counting_not_an_empirical_probability_law",
            "box_even_fields": len(box), "scatter_closed_fields": len(xs), "references": len(refs),
            "nonempty_clock_fibers": nonempty, "ticket_scatter_inverse_and_clock_checks": total,
            "S4_covariance_checks_on_both_maps": equiv, "lower_controls": lower_controls(),
            "transport_only_six_frame_control": six_frame_comparison(xs),
            "combined_command_countercontrol": {"localized": loc, "scattered": sx[loc],
                "ports_seen_while_scattered": observed, "ports_in_full_scattered_clock": list(PORTS)},
            "uniform_initial_phase_control": {"field": ones, "successive_pairs": sorted(pairs),
                                              "reverse_pairs_present": 0, "iid_pairs_if_independent": 16},
            "resource_boundary": "Fixed-field noninvasive full-period counting uses one visit per supplied ticket; "
            "unknown phase alone is not a probability distribution or exchangeability. No local clock, backaction "
            "law, physical preparation, scheduling, or time-reversal covariance of the tick is derived."}


if __name__ == "__main__":
    print(json.dumps(probe(), sort_keys=True))
