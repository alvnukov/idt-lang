"""Exact eight-setting visibility controls; an external reader, not a native Z8 gate.

Run: python3 -m scripts.probe_phase_visibility_controls

Target P(D0|x,y)=(1+V cos(pi*(x-y)/4))/2, 0<=V<=1. Each arm sees only
its own setting and setting-independent shared stock; decoder sees the two
symbols and may use that stock. No disposal of unresolved launches. At the
boundary we supply the relative jitter/label stock (including irrational
mixture weights); these are not generated by the native four-phase schedule.
Common-mode rotation alone does not move x-y. A fair flat branch attains any
lower visibility via a supplied convex weight. No physics or data are fitted.

The three-cell diagnostic is a different null: a static triangle on a common
calibrated ramp with a setting-independent affine background/contrast. A
single-knob curve cannot by itself certify independent arm choices, absence
of timing signals, setting-independent stock, or uniform losses. In particular
an uncalibrated relative knob can reparametrize a whole cosine as a triangle:
on 0<=theta<=pi, 1-g(theta)/pi=(1+cos(theta))/2 for
g(theta)=pi*(1-cos(theta))/2. This need not split into two local arm maps.

Empirical scope: Brida et al., JPSJ 82 (2013) 034004 (doi:10.7566/JPSJ.82.034004),
https://arxiv.org/html/1303.5281#S3.F4, scanned a slow arm bias, comparing
an opposite arm fixed at 0 or pi/2 with switching per herald. Fig. 4(a) plots
one output's raw detections and herald counts; (b,c) compare normalized
curves; displayed uncertainties have k=1. Their reduced chi-squared around
0.98 vs above 20 (Fig. 5) is for their QM and specified memory-model curves.
The authors discuss manufacturer-estimated phase crosstalk up to 20% in the
opposite arm. A published Comment (doi:10.7566/JPSJ.82.086001) disputes the
independent-component interpretation, simulating the integrated device instead;
the Reply (doi:10.7566/JPSJ.82.086002) distinguishes this from the proposed
noncommunicating memories. The exchange is not a new experimental replication.
This is not our three-cell statistic or the balanced two-arm setting game:
no per-launch two-output dataset or independent replication is asserted here.
"""

import json
from fractions import Fraction as F
from itertools import product

from scripts import probe_eight_angle_reader_boundary as reader


# A pair (a,b) denotes a+b*sqrt(2), with rational coefficients.
def blend(plain, altered, weight):
    """Rational plain/altered probabilities; quadratic weight selects altered."""
    a, b = weight
    return plain + (altered-plain)*a, (altered-plain)*b


def binary_jitter(x, y, *, center=(-1, 1)):
    """Shift one arm by 0 with weight sqrt(2)-1, otherwise uniformly ±1.

    The third harmonic multiplier is w+(1-w)cos(3*pi/4)=0 at this weight.
    A random *common* shift of both arms would leave every difference intact.
    """
    shifted = (reader.triangle_probability(x, y-1) + reader.triangle_probability(x, y+1))/2
    return blend(shifted, reader.triangle_probability(x, y), center)


def trit_modes(x, y):
    """Local trits; a uniform optional Z3 offset disconnects *even* differences.

    Odd-distance inputs shift both names or neither, leaving equality intact.
    On even-distance inputs one name shifts uniformly, hence equality is 1/3
    before the fair equality/complement switch, and the final mean is 1/2.
    """
    def replay(offsets):
        wins = 0
        for k, flip, offset in product(range(8), range(2), offsets):
            a = (reader.TRITS[(x+k) % 8] + (x % 2)*offset) % 3
            b = (reader.TRITS[(y+k+4*flip) % 8] + (1-y % 2)*offset) % 3
            wins += (a == b) ^ flip
        return F(wins, 16*len(offsets))
    return replay((0,)), replay(range(3))


def trit_boundary(x, y):
    """Keep names with supplied probability 5*sqrt(2)/8; else scramble."""
    plain, scrambled = trit_modes(x, y)
    return blend(scrambled, plain, (0, F(5, 8)))


COS = ((1, 0), (0, F(1, 2)), (0, 0), (0, F(-1, 2)),
       (-1, 0), (0, F(-1, 2)), (0, 0), (0, F(1, 2)))


def triangle_cosine_coefficient(harmonic):
    """2/8 times the cosine projection on the registered Z8 grid (no jitter)."""
    samples = [reader.triangle_probability(d, 0) for d in range(8)]
    return tuple(sum(p*COS[harmonic*d % 8][j] for d, p in enumerate(samples))/4
                 for j in range(2))


def curvature_interval(counts, *, allowance=F(0)):
    """Conservative K=2*p1-p0-p2 on three registered settings of *one* ramp.

    Counts per cell are (D0,D1,total launched), not conditioned on being
    detected. Missing/no launches admit [0,1]. The optional per-cell absolute
    probability allowance must separately cover any claimed *simultaneous*
    statistical and calibration uncertainty. The default describes the
    observed launches only: it is not a population confidence interval.
    For the piecewise-linear extension of the registered triangle, per-cell
    phase errors <=h grid steps perturb p by <=h/4 for absolute contrast <=1.
    Other calibration errors need their own bound. Offset and contrast must
    be common across cells. Sign-definite K only excludes that static ramp.
    """
    if not 0 <= allowance <= 1:
        raise ValueError("invalid per-cell absolute allowance")
    bounds = []
    for d in range(3):
        n0, n1, n = counts.get(d, (0, 0, 0))
        if any(type(v) is not int or v < 0 for v in (n0, n1, n)) or n0+n1 > n:
            raise ValueError("invalid all-launch counts")
        if n:
            bounds.append((max(0, F(n0, n)-allowance), min(1, F(n-n1, n)+allowance)))
        else:
            bounds.append((0, 1))
    (l0, u0), (l1, u1), (l2, u2) = bounds
    return 2*l1-u0-u2, 2*u1-l0-l2


def verify():
    caps = [reader.block_cap(2, 4), reader.block_cap(3, 3)]
    if caps != [12, 13]:
        raise ValueError("mixed parity block bound changed")
    for x, y in product(range(8), repeat=2):
        ca, cb = COS[(x-y) % 8]
        for c, p in ((F(1, 2), binary_jitter(x, y)), (F(5, 8), trit_boundary(x, y))):
            # Multiply V=c*sqrt(2) by cos=ca+cb*sqrt(2), then add DC.
            if p != (F(1, 2) + c*cb, c*ca/2):
                raise ValueError(f"quadratic probability mismatch at {(x, y)}")
    if (triangle_cosine_coefficient(1), triangle_cosine_coefficient(3)) != (
            (F(1, 4), F(1, 8)), (F(1, 4), F(-1, 8))):
        raise ValueError("registered triangle spectrum mismatch")
    return {"checked_external_cells": 64, "mixed_block_win_caps_of_16": caps,
            "odd_win_probability": "1/2 + V*sqrt(2)/4",
            "max_visibility_any_binary_side": "1/sqrt(2)",
            "attained_by_binary_equality_center_weight": "sqrt(2)-1",
            "max_visibility_two_trits_shared_stock_decoder": "5*sqrt(2)/8",
            "attained_by_trit_plain_weight": "5*sqrt(2)/8",
            "static_triangle_abs_third_over_first_nonzero_contrast": "3-2*sqrt(2)",
            "registered_three_cell_curvature": {"static_affine_triangle": "0",
                                                "supplied_cosine": "(sqrt(2)-1)*V/2"},
            "scope": "finite external reader comparison only; no experimental exclusion"}


if __name__ == "__main__":
    print(json.dumps(verify(), sort_keys=True, indent=2))
