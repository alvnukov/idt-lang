"""Label-free packet returns in the known staggered Rule 54 on a supplied line.

Compare trajectories of (periodic medium, medium XOR finite perturbation).
An exact return translates BOTH configurations and the next matching. The
initial medium is prescribed, not generated by the packet. Speeds are measured
in supplied lattice sites per matching half-step, not physical units.

There is also an elementary vacuum edge argument, independent of census size.
Take the leftmost occupied site m in any nonempty finite configuration on Z.
If passive, m persists and gives birth to m-1, which is passive next: the left
edge then moves left forever. If active with an occupied right neighbor, m
clears; m+1 persists and is active next. Otherwise m stays and is passive
next. Thus edge increments are all +1, or eventually all -1. An exact return
up to a clock-compatible translation repeats by covariance of the rule. Its
periodic edge increments must therefore be constant +1 or -1. This excludes
an exact finite-support vacuum packet at any other speed, not a detector
signature, centroid, or defect on a nonzero background. This is a mathematical
argument accompanied by local executable checks, not a Lean proof.

Prior work: Klobas et al., https://arxiv.org/abs/1807.05000, describe bare
solitons, collision delays and an effective speed 1/3. Here we compare entire
relative configurations and do not identify a defect with a tagged soliton.

Run: python3 -m scripts.probe_binary_rest_packets
"""

from __future__ import annotations

import json
from collections import Counter
from collections.abc import Iterator
from dataclasses import asdict, dataclass
from fractions import Fraction
from itertools import islice

from scripts.probe_binary_cycle_solitons import Cycle


@dataclass(frozen=True)
class ReturnCheck:
    elapsed: int
    displacement: int
    shape: bool
    medium: bool
    clock: bool

    @property
    def exact(self) -> bool:
        return self.shape and self.medium and self.clock


def _left_edge(bits: int) -> int:
    if not bits:
        raise RuntimeError("a nonzero difference vanished under a reversible update")
    return (bits & -bits).bit_length() - 1


class GuardedLine:
    """A periodic bulk and its finite change, represented on a causally padded ring."""

    def __init__(self, width: int, horizon: int, period: int):
        if width < 1 or horizon < 1 or period < 2 or period % 2:
            raise ValueError("positive width/horizon and an even tiling period >= 2 required")
        self.width, self.horizon, self.period = width, horizon, period
        # Origin is a multiple of period, so bit 0 in the word is at the launch
        # origin. More than horizon sites on each side prevent wound differences.
        self.origin = ((horizon // period) + 1) * period
        needed = self.origin + width + horizon + 1
        self.cycle = Cycle(((needed + period - 1) // period) * period)
        self.tiling = self.cycle.full // ((1 << period) - 1)

    def _launch(self, word: int, mask: int, phase: int) -> tuple[int, int]:
        if not (0 <= word < 1 << self.period and 0 < mask < 1 << self.width and phase in (0, 1)):
            raise ValueError("invalid periodic word, nonzero finite launch mask or next matching")
        bulk = self.tiling * word
        return bulk, bulk ^ (mask << self.origin)

    def _translate(self, bits: int, dx: int) -> int:
        n = self.cycle.n
        dx %= n
        return ((bits << dx) & self.cycle.full) | (bits >> (n - dx))

    def charge_difference(self, word: int, mask: int, phase: int) -> tuple[int, int]:
        # Extensive medium charges are not defined on Z. Their difference is:
        # the local density changes only in a finite neighborhood of the launch.
        b, x = self._launch(word, mask, phase)
        br, bl = self.cycle.counts(b, phase)
        xr, xl = self.cycle.counts(x, phase)
        return xr - br, xl - bl

    def replay(self, word: int, mask: int, phase: int, *, raw: bool = False) -> Iterator[ReturnCheck]:
        b0, x0 = self._launch(word, mask, phase)
        b, x = b0, x0
        initial_delta = x0 ^ b0
        anchor = _left_edge(initial_delta)
        template = initial_delta >> anchor
        step = self.cycle.raw_half_step if raw else self.cycle.half_step
        for t in range(1, self.horizon + 1):
            b, x = step(b, phase), step(x, phase)
            phase ^= 1
            delta = b ^ x
            left = _left_edge(delta)
            if left < self.origin - t or delta.bit_length() > self.origin + self.width + t:
                raise RuntimeError("finite change escaped its radius-one causal cone")
            dx = left - anchor  # lifted on the line, not reduced modulo circumference
            # Matching phase is part of the state and transforms under odd shifts.
            # Shape plus bulk equality is equivalent to equality of the full pair.
            yield ReturnCheck(t, dx, (delta >> left) == template,
                              b == self._translate(b0, dx), (t - dx) % 2 == 0)


def census(line: GuardedLine, words: range) -> dict:
    """Anchoring the first changed bit removes empty/leading-zero duplications."""
    speeds: Counter[str] = Counter()
    neutral: Counter[str] = Counter()
    launches = 0
    for word in words:  # indexed medium phases, including all launch alignments
        for phase in (0, 1):
            for mask in range(1, 1 << line.width, 2):
                launches += 1
                hit = next((r for r in line.replay(word, mask, phase) if r.exact), None)
                if hit is not None:
                    v = str(Fraction(hit.displacement, hit.elapsed))
                    speeds[v] += 1
                    if line.charge_difference(word, mask, phase) == (0, 0):
                        neutral[v] += 1
    return {"width_at_most": line.width, "horizon_half_steps": line.horizon,
            "tiling_period": line.period, "indexed_words": len(words),
            "launches": launches, "first_return_speeds": dict(speeds),
            "neutral_first_return_speeds": dict(neutral),
            "no_return_through_horizon": launches - sum(speeds.values())}


def vacuum_edge_checks() -> int:
    """Check the edge and next-edge activity for all four local cases and 16 tails."""
    cycle = Cycle(16)
    m = 4
    checked = 0
    for phase in (0, 1):
        for right in (0, 1):
            for tail in range(16):
                x = ((1 | (right << 1) | (tail << 2)) << m)
                edge = _left_edge(cycle.raw_half_step(x, phase))
                active = m % 2 == phase
                expected = (m + right if active else m - 1)
                if edge != expected or (edge % 2 == (phase ^ 1)) != (active and bool(right)):
                    raise RuntimeError("vacuum edge transition changed")
                checked += 1
    return checked


def winding_control() -> dict:
    cycle = Cycle(8)
    start = x = 3
    for t in range(8):
        x = cycle.raw_half_step(x, t % 2)
    end = list(GuardedLine(2, 8, 2).replay(0, 3, 0, raw=True))[-1]
    if not (x == start and end.exact and end.displacement == 8):
        raise RuntimeError("winding control changed")
    return {"ring_size": 8, "half_steps": 8, "same_ring_state_and_clock": True,
            "lifted_line_displacement": end.displacement}


def experiment() -> dict:
    medium_line = GuardedLine(6, 12, 4)
    example = []
    for word in (0, 1, 5):
        for phase in (0, 1):
            r = next(r for r in medium_line.replay(word, 3, phase, raw=True) if r.exact)
            example.append({"background_bitmask_period_4": word, "xor_mask": 3,
                            "next_matching": phase, "return_half_steps": r.elapsed,
                            "line_displacement": r.displacement,
                            "charge_difference_R_L": medium_line.charge_difference(word, 3, phase)})
    return {"criterion": "translate the entire medium, finite difference, and next matching",
            "vacuum": census(GuardedLine(12, 24, 2), range(1)),
            "periodic": census(medium_line, range(16)),
            "adjacent_change_examples": example, "vacuum_local_edge_checks": vacuum_edge_checks(),
            "false_rest_control_launch": {"background_bitmask_period_4": 5, "xor_mask": 1,
                                          "next_matching": 0},
            "false_rest_controls": [asdict(r) for r in
                                    islice(medium_line.replay(5, 1, 0, raw=True), 2)],
            "compact_winding_control": winding_control()}


if __name__ == "__main__":
    print(json.dumps(experiment(), indent=2))
