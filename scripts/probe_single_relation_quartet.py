"""Finite clean-quartet compilers on one symmetric Boolean relation.

Diagonal entries are site occupations; off-diagonal entries are bonds. Offers
specify an unordered pair, and only its two diagonals and its bond can change.
The contact set and schedule are supplied, not generated by the relation. These
are finite gate and scheduler controls, not a minimality or geometry claim.
"""

from __future__ import annotations

import json
from collections import Counter, deque
from collections.abc import Callable, Iterable
from enum import Enum
from itertools import combinations, permutations, product
from math import gcd
from typing import NamedTuple

Pair = tuple[int, int]
Word = tuple[Pair, ...]
Table = tuple[int, int, int]


class State(NamedTuple):
    """Two bit masks for the diagonal and strict upper triangle of one relation."""

    sites: int
    bonds: int


class Rule(Enum):
    PARITY = "degree_parity"
    DEGREE = "exact_degree"


OfferRule = Rule | int | Table

PARITY_WORD: Word = (
    (0, 1),
    (0, 2),
    (0, 3),
    (2, 3),
    (1, 3),
    (0, 3),
    (0, 1),
    (0, 2),
    (2, 3),
    (1, 3),
    (0, 3),
    (0, 1),
    (1, 3),
    (0, 2),
    (2, 3),
)
NO_DEGREE_MOTIF: Word = (
    (0, 1),
    (0, 2),
    (0, 1),
    (2, 3),
    (0, 3),
    (0, 2),
    (0, 3),
    (2, 3),
    (0, 2),
)
NO_DEGREE_WORD = NO_DEGREE_MOTIF * 16
NO_DEGREE_CODE = 7
BRANCHING_CONTACTS: Word = ((0, 2), (0, 4), (1, 2), (2, 3))
BRANCHING_WORD: Word = (
    (0, 4),
    (1, 2),
    (0, 2),
    (1, 2),
    (2, 3),
    (1, 2),
    (2, 3),
    (0, 2),
    (0, 4),
    (2, 3),
)


class _Contact(NamedTuple):
    pair: Pair
    edge: int
    both_sites: int
    outside_left: int
    outside_right: int


def _row_action(state: State, contact: _Contact, code: int, unlike: bool) -> State:
    """Codes 6–11 add the same-diagonal toggle to the corresponding 0–5 row."""
    sites, bonds = state
    if not unlike:
        return State(sites, bonds ^ contact.edge) if code >= 6 else state
    row = code % 6
    linked = bool(bonds & contact.edge)
    if row in (3, 5) or (row == 1 and not linked) or (row == 2 and linked):
        sites ^= contact.both_sites
    if row >= 4:
        bonds ^= contact.edge
    return State(sites, bonds)


def _offer(state: State, contact: _Contact | None, rule: OfferRule) -> State:
    if contact is None:
        return state
    a, b = contact.pair
    unlike = bool(((state.sites >> a) ^ (state.sites >> b)) & 1)
    if isinstance(rule, int):
        return _row_action(state, contact, rule, unlike)
    if isinstance(rule, Rule) and not unlike:
        return state
    left = (state.bonds & contact.outside_left).bit_count()
    right = (state.bonds & contact.outside_right).bit_count()
    if isinstance(rule, tuple):
        # The unordered outside-degree blocks are (0,0), (0,1), (1,1).
        return (
            _row_action(state, contact, rule[left + right], unlike)
            if max(left, right) <= 1
            else state
        )
    # Adding the shared bond to both degrees preserves equality and parity
    # equality. Excluding it makes the controlling bits unchanged by toggling.
    equal = left == right if rule is Rule.DEGREE else (left - right) % 2 == 0
    return _row_action(state, contact, 4 if equal else 2, unlike)


def _validate_rule(rule: OfferRule) -> None:
    if isinstance(rule, Rule):
        return
    if isinstance(rule, int) and 0 <= rule < 12:
        return
    if (
        isinstance(rule, tuple)
        and len(rule) == 3
        and all(isinstance(code, int) and 0 <= code < 12 for code in rule)
    ):
        return
    raise ValueError(f"invalid local rule: {rule!r}")


class Relation:
    """Layout and offered contacts, with complete contacts by default.

    Bond indices always use all lexicographic pairs, even on sparse contact
    fixtures. An offer outside the contact set is idle, not a dynamic update.
    """

    def __init__(self, size: int, contacts: Iterable[Pair] | None = None) -> None:
        if size < 1:
            raise ValueError("relation must have at least one site")
        self.size = size
        self.pairs = tuple(combinations(range(size), 2))
        self._edges = {pair: 1 << k for k, pair in enumerate(self.pairs)}
        self.contacts = (
            self.pairs
            if contacts is None
            else tuple(sorted({self._pair(p) for p in contacts}))
        )
        incident = [0] * size
        for (a, b), edge in self._edges.items():
            incident[a] |= edge
            incident[b] |= edge
        self._incident = tuple(incident)
        self._contacts = {
            (a, b): _Contact(
                (a, b),
                (edge := self._edges[a, b]),
                (1 << a) | (1 << b),
                incident[a] ^ edge,
                incident[b] ^ edge,
            )
            for a, b in self.contacts
        }

    def _pair(self, pair: Pair) -> Pair:
        a, b = pair
        ordered = (min(a, b), max(a, b))
        if ordered not in self._edges:
            raise ValueError(f"invalid pair {pair!r} for {self.size} sites")
        return ordered

    def state(self, sites: int, bonds: Iterable[Pair] = ()) -> State:
        if not 0 <= sites < 1 << self.size:
            raise ValueError(f"diagonal mask {sites!r} exceeds the relation size")
        return State(sites, sum({self._edges[self._pair(pair)] for pair in bonds}))

    def degrees(self, state: State) -> tuple[int, ...]:
        return tuple((state.bonds & mask).bit_count() for mask in self._incident)

    def offer(self, before: State, pair: Pair, rule: OfferRule = Rule.PARITY) -> State:
        """Apply one unordered off-diagonal offer under the selected rule."""
        _validate_rule(rule)
        return _offer(before, self._contacts.get(self._pair(pair)), rule)

    def compile_word(
        self, word: Iterable[Pair], rule: OfferRule = Rule.PARITY
    ) -> Callable[[State], State]:
        """Compile the fixed left-to-right offer word into a reusable map."""
        _validate_rule(rule)
        contacts = tuple(self._contacts.get(self._pair(pair)) for pair in word)

        def apply(before: State) -> State:
            for contact in contacts:
                before = _offer(before, contact, rule)
            return before

        return apply

    def replay(
        self, before: State, word: Iterable[Pair], rule: OfferRule = Rule.PARITY
    ) -> tuple[State, int]:
        """Return final relation and the count of offers changing it."""
        _validate_rule(rule)
        effective = 0
        for pair in word:
            after = _offer(before, self._contacts.get(self._pair(pair)), rule)
            effective += after != before
            before = after
        return before, effective


_CLEAN = tuple(State(sites, 0) for sites in range(16))
_TARGET = tuple(
    State(sites ^ 15 if sites.bit_count() == 2 else sites, 0) for sites in range(16)
)


def _require_quartet(layout: Relation) -> None:
    if layout.size != 4 or layout.contacts != layout.pairs:
        raise ValueError("this census needs the complete four-site contact layout")


def _correct_inputs(layout: Relation, word: Word, rule: OfferRule = Rule.PARITY) -> int:
    apply = layout.compile_word(word, rule)
    return sum(
        apply(before) == target for before, target in zip(_CLEAN, _TARGET, strict=True)
    )


class _Relabeling(NamedTuple):
    sites: tuple[int, ...]
    bonds: tuple[int, ...]
    pairs: Word


def _permute_mask(mask: int, destination_bits: tuple[int, ...]) -> int:
    return sum(bit for index, bit in enumerate(destination_bits) if mask >> index & 1)


def _relabeling(layout: Relation, permutation: list[int]) -> _Relabeling:
    site_bits = tuple(1 << image for image in permutation)
    pairs = tuple(
        (min(permutation[i], permutation[j]), max(permutation[i], permutation[j]))
        for i, j in layout.pairs
    )
    edge_bits = tuple(layout.state(0, (pair,)).bonds for pair in pairs)
    return _Relabeling(site_bits, edge_bits, pairs)


def audit_offer_laws(layout: Relation) -> int:
    """Check involution, bit reflection, relabeling generators and conservation."""
    if layout.contacts != layout.pairs:
        raise ValueError("relabeling audit needs a complete contact layout")
    relabelings: list[_Relabeling] = []
    for i in range(layout.size - 1):
        permutation = list(range(layout.size))
        permutation[i], permutation[i + 1] = permutation[i + 1], permutation[i]
        relabelings.append(_relabeling(layout, permutation))
    visited = 0
    reflection = (1 << layout.size) - 1
    for sites, bonds in product(range(reflection + 1), range(1 << len(layout.pairs))):
        before = State(sites, bonds)
        for k, (a, b) in enumerate(layout.pairs):
            for rule in Rule:
                after = layout.offer(before, (a, b), rule)
                reflected = layout.offer(State(sites ^ reflection, bonds), (a, b), rule)
                if (
                    before != layout.offer(after, (a, b), rule)
                    or sites.bit_count() != after.sites.bit_count()
                    or (sites ^ after.sites) & ~((1 << a) | (1 << b))
                    or (bonds ^ after.bonds) & ~(1 << k)
                    or reflected != State(after.sites ^ reflection, after.bonds)
                ):
                    raise ValueError(f"offer law failed: {before}, {(a, b)}, {rule}")
                for relabel in relabelings:
                    actual = layout.offer(
                        _remap(before, relabel), relabel.pairs[k], rule
                    )
                    if actual != _remap(after, relabel):
                        raise ValueError(
                            f"relabeling failed: {before}, {(a, b)}, {rule}"
                        )
                visited += 1
    return visited


def _remap(state: State, relabel: _Relabeling) -> State:
    return State(
        _permute_mask(state.sites, relabel.sites),
        _permute_mask(state.bonds, relabel.bonds),
    )


def audit_degree_cap() -> int:
    """Compare every offer staying within dynamic degree two, on five sites."""
    layout = Relation(5)
    count = 0
    for bonds in range(1 << len(layout.pairs)):
        if max(layout.degrees(State(0, bonds))) > 2:
            continue
        for sites, pair in product(range(1 << layout.size), layout.pairs):
            before = State(sites, bonds)
            parity = layout.offer(before, pair, Rule.PARITY)
            degree = layout.offer(before, pair, Rule.DEGREE)
            # The only possible disagreement is an unlinked 0-vs-2 offer
            # toggling the parity bond and hence raising the 2 to a 3. Such
            # an offer is unavailable if the contact graph has max degree 2
            # and all dynamic bonds are contacts.
            if max(layout.degrees(parity)) <= 2:
                if parity != degree:
                    raise ValueError(f"within-cap separation: {before}, {pair}")
                count += 1
    return count


class CleanOrbit(NamedTuple):
    states: int
    clean_distances: tuple[int, ...]


def clean_orbit(layout: Relation, rule: Rule) -> CleanOrbit:
    """BFS in unit proposal distance from the clean two-mark input {0,1}."""
    start = layout.state(0b11)
    seen = {start: 0}
    queue = deque((start,))
    while queue:
        before = queue.popleft()
        for contact in layout._contacts.values():
            after = _offer(before, contact, rule)
            if after not in seen:
                seen[after] = seen[before] + 1
                queue.append(after)
    return CleanOrbit(
        len(seen), tuple(sorted(d for state, d in seen.items() if not state.bonds))
    )


class BranchingSeparation(NamedTuple):
    first_offer: int
    degrees: Pair
    parity: State
    degree: State


def branching_separator() -> BranchingSeparation:
    layout = Relation(5, BRANCHING_CONTACTS)
    parity = degree = layout.state(0b11)
    first_offer = 0
    degrees = (0, 0)
    for index, (a, b) in enumerate(BRANCHING_WORD, start=1):
        before = parity
        parity = layout.offer(parity, (a, b), Rule.PARITY)
        degree = layout.offer(degree, (a, b), Rule.DEGREE)
        if not first_offer and parity != degree:
            first_offer = index
            all_degrees = layout.degrees(before)
            degrees = (all_degrees[a], all_degrees[b])
    return BranchingSeparation(first_offer, degrees, parity, degree)


class TableCensus(NamedTuple):
    hits: tuple[Table, ...]
    correct_inputs: dict[int, int]


def capped_table_census(layout: Relation) -> TableCensus:
    _require_quartet(layout)
    hits: list[Table] = []
    histogram: Counter[int] = Counter()
    for table in product(range(12), range(12), range(12)):
        count = _correct_inputs(layout, PARITY_WORD, table)
        histogram[count] += 1
        if count == len(_CLEAN):
            hits.append(table)
    return TableCensus(tuple(hits), dict(histogram))


class SingleEdits(NamedTuple):
    deletion_hits: int
    deletions: int
    substitution_hits: int
    substitutions: int


def single_edit_scan(layout: Relation) -> SingleEdits:
    _require_quartet(layout)
    deletion_hits = substitution_hits = substitutions = 0
    for i, pair in enumerate(PARITY_WORD):
        prefix, suffix = PARITY_WORD[:i], PARITY_WORD[i + 1 :]
        deletion_hits += _correct_inputs(layout, prefix + suffix) == len(_CLEAN)
        for replacement in layout.pairs:
            if replacement != pair:
                substitutions += 1
                substitution_hits += _correct_inputs(
                    layout, prefix + (replacement,) + suffix
                ) == len(_CLEAN)
    return SingleEdits(
        deletion_hits, len(PARITY_WORD), substitution_hits, substitutions
    )


class NoDegreeWord(NamedTuple):
    period: int
    target_motifs: tuple[int, ...]
    all_equal_effective: tuple[int, int]


def no_degree_word_census(layout: Relation) -> NoDegreeWord:
    _require_quartet(layout)
    apply = layout.compile_word(NO_DEGREE_MOTIF, NO_DEGREE_CODE)
    states = _CLEAN
    motifs = 0
    hits: list[int] = []
    while True:
        motifs += 1
        states = tuple(apply(state) for state in states)
        if states == _CLEAN:
            break
        if states == _TARGET:
            hits.append(motifs)
    _, zero = layout.replay(_CLEAN[0], NO_DEGREE_WORD, NO_DEGREE_CODE)
    _, one = layout.replay(_CLEAN[-1], NO_DEGREE_WORD, NO_DEGREE_CODE)
    return NoDegreeWord(motifs, tuple(hits), (zero, one))


def scan_no_degree_controls(
    layout: Relation,
) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """Replay control words for the analytical split of the other 11 codes.

    Codes 0,4,6,10 never swap. Codes 2,8 swap unlike bits only on a linked
    pair; 2 never creates a clean-start bond, and 8 creates bonds only when
    bits are equal. For 8, with no previous swap such bonds remain equal, so a
    first swap is impossible. Codes 1,3,5,9,11 project to the offered site
    transposition (1 never changes the initially empty bonds). In particular
    none of these 11 controls can fix all singleton inputs while complementing
    the two-mark masks, even without a clean-output requirement.
    """
    _require_quartet(layout)
    raw = (0, 2, 4, 6, 8, 10)
    fixed = (1, 3, 5, 9, 11)
    for word in (PARITY_WORD, NO_DEGREE_WORD, layout.pairs):
        for code in raw + fixed:
            apply = layout.compile_word(word, code)
            site_word = layout.compile_word(word, 3)
            for state in _CLEAN:
                expected = state.sites if code in raw else site_word(state).sites
                if apply(state).sites != expected:
                    raise ValueError(f"no-degree control failed: {code}, {state}")
    return raw, fixed


def parity_round_robin(layout: Relation) -> dict[int | None, int]:
    """Repeated schedules, observed after each offer, one balanced input."""
    _require_quartet(layout)
    start, target = _CLEAN[0b0011], _TARGET[0b0011]
    counts: Counter[int | None] = Counter()
    for pairs in permutations(layout.contacts):
        contacts = tuple(layout._contacts[pair] for pair in pairs)
        before = start
        offers = 0
        while True:
            before = _offer(before, contacts[offers % len(contacts)], Rule.PARITY)
            offers += 1
            if before == target:
                counts[offers] += 1
                break
            if before == start and offers % len(contacts) == 0:
                # The state and phase together form a finite permutation.
                counts[None] += 1
                break
    return dict(counts)


class RoundRobinCensus(NamedTuple):
    hits: int
    missing_target: int
    incompatible_phases: int


def _cycle_congruence(
    apply: Callable[[State], State], start: State, target: State
) -> tuple[int, int] | None:
    """Return the target residue and orbit period for a finite permutation."""
    residue = 0 if start == target else None
    state = apply(start)
    period = 1
    while state != start:
        if state == target:
            residue = period
        state = apply(state)
        period += 1
    return (residue, period) if residue is not None else None


def _common_round_exists(phases: Iterable[tuple[int, int]]) -> bool:
    # Non-coprime CRT: the common round count exists iff every two residues
    # agree modulo the gcd of their periods.
    return all((r - s) % gcd(p, q) == 0 for (r, p), (s, q) in combinations(phases, 2))


def no_degree_round_robin(layout: Relation) -> RoundRobinCensus:
    """Powers of each one-round permutation, checked on the full truth table."""
    _require_quartet(layout)
    hits = missing = incompatible = 0
    for pairs in permutations(layout.contacts):
        apply = layout.compile_word(pairs, NO_DEGREE_CODE)
        phases: list[tuple[int, int]] = []
        for start, target in zip(_CLEAN, _TARGET, strict=True):
            phase = _cycle_congruence(apply, start, target)
            if phase is None:
                missing += 1
                break
            phases.append(phase)
        else:
            if _common_round_exists(phases):
                hits += 1
            else:
                incompatible += 1
    return RoundRobinCensus(hits, missing, incompatible)


def report() -> dict[str, object]:
    four = Relation(4)
    five = Relation(5)
    raw, fixed = scan_no_degree_controls(four)
    parity_rounds = parity_round_robin(four)
    return {
        "scope": "finite supplied-contact and supplied-schedule probe; no global minimality claim",
        "target": "clean identity except for complementing the two-mark inputs",
        "offer_law_cases": audit_offer_laws(four),
        "degree_cap_comparisons": audit_degree_cap(),
        "parity_word": PARITY_WORD,
        "parity_word_inputs": _correct_inputs(four, PARITY_WORD),
        "parity_effective_offers_in_mask_order": [
            four.replay(state, PARITY_WORD)[1] for state in _CLEAN
        ],
        "parity_single_edits": single_edit_scan(four)._asdict(),
        "four_site_parity_orbit": clean_orbit(four, Rule.PARITY)._asdict(),
        "five_site_parity_orbit": clean_orbit(five, Rule.PARITY)._asdict(),
        "five_site_degree_orbit": clean_orbit(five, Rule.DEGREE)._asdict(),
        "branching_contacts": BRANCHING_CONTACTS,
        "branching_word": BRANCHING_WORD,
        "branching_separator": branching_separator()._asdict(),
        "capped_table_census": capped_table_census(four)._asdict(),
        "parity_round_robin_one_input_after_every_offer": {
            "start_marks": (0, 1),
            "target_marks": (2, 3),
            "misses": parity_rounds.get(None, 0),
            "first_hit_steps": {
                step: count for step, count in parity_rounds.items() if step is not None
            },
        },
        "no_degree_motif": NO_DEGREE_MOTIF,
        "no_degree_code": NO_DEGREE_CODE,
        "no_degree_word_inputs": _correct_inputs(four, NO_DEGREE_WORD, NO_DEGREE_CODE),
        "no_degree_word_offers": len(NO_DEGREE_WORD),
        "no_degree_word_census": no_degree_word_census(four)._asdict(),
        "no_degree_controls": {
            "preserve_diagonals": raw,
            "fixed_site_permutation": fixed,
        },
        "no_degree_round_robin_all_inputs_at_round_boundaries": no_degree_round_robin(
            four
        )._asdict(),
    }


if __name__ == "__main__":
    print(json.dumps(report(), indent=2, sort_keys=True))
